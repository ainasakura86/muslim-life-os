## Untuk user baru
1. Buka link di Safari (iPhone) atau Chrome (Android)
2. Add to Home Screen
3. Family Mode → Daftar akaun (email + password)
4. Parent: Cipta keluarga → share kod ML-XXXX
5. Ahli lain: Daftar → Join kod → tick solat

